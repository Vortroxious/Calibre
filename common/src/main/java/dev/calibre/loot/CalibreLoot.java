package dev.calibre.loot;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import dev.calibre.Calibre;
import dev.calibre.gun.GunItem;
import dev.calibre.gun.GunState;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;
import net.minecraft.util.RandomSource;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;

import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.function.Consumer;

/**
 * Extra chest loot. The same weighted pools are used by NeoForge (a global loot modifier, data/calibre/loot_modifiers)
 * and Fabric (calibre_gen/loot.json, applied when a matching loot table generates its drops). Generated by tools/gen_data.py.
 */
public final class CalibreLoot {
    public record Entry(Item item, int weight, int min, int max) {
        public static final Codec<Entry> CODEC = RecordCodecBuilder.create(i -> i.group(
                BuiltInRegistries.ITEM.byNameCodec().fieldOf("item").forGetter(Entry::item),
                Codec.INT.optionalFieldOf("weight", 1).forGetter(Entry::weight),
                Codec.INT.optionalFieldOf("min", 1).forGetter(Entry::min),
                Codec.INT.optionalFieldOf("max", 1).forGetter(Entry::max)
        ).apply(i, Entry::new));
    }

    /** one loot modifier: the loot tables it applies to and what it adds */
    public record Pool(List<Identifier> tables, List<Entry> entries, float chance, int rolls) {}

    private CalibreLoot() {}

    /** Adds up to `rolls` weighted picks (each with probability `chance`). Guns come partially loaded. */
    public static void roll(List<Entry> entries, float chance, int rolls, RandomSource random, Consumer<ItemStack> out) {
        int total = 0;
        for (Entry e : entries) total += e.weight;
        if (total <= 0) return;
        for (int r = 0; r < rolls; r++) {
            if (random.nextFloat() > chance) continue;
            int pick = random.nextInt(total);
            for (Entry e : entries) {
                pick -= e.weight;
                if (pick < 0) {
                    int n = e.min + (e.max > e.min ? random.nextInt(e.max - e.min + 1) : 0);
                    ItemStack st = new ItemStack(e.item, n);
                    if (st.getItem() instanceof GunItem gun) {
                        int ammo = random.nextInt(gun.def().magSize() + 1);
                        GunItem.setState(st, new GunState(ammo, false, 0));
                    }
                    out.accept(st);
                    break;
                }
            }
        }
    }

    /** Reads calibre_gen/loot.json (Fabric). Call after items are registered. */
    public static List<Pool> load() {
        List<Pool> pools = new ArrayList<>();
        try (var in = CalibreLoot.class.getResourceAsStream("/calibre_gen/loot.json")) {
            if (in == null) return pools;
            JsonObject root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            for (var e : root.entrySet()) {
                JsonObject o = e.getValue().getAsJsonObject();
                List<Identifier> tables = new ArrayList<>();
                for (JsonElement t : o.getAsJsonArray("tables")) tables.add(Identifier.parse(t.getAsString()));
                List<Entry> entries = new ArrayList<>();
                for (JsonElement x : o.getAsJsonArray("entries")) {
                    JsonObject j = x.getAsJsonObject();
                    Item item = BuiltInRegistries.ITEM.getValue(Identifier.parse(j.get("item").getAsString()));
                    entries.add(new Entry(item, j.has("weight") ? j.get("weight").getAsInt() : 1,
                            j.has("min") ? j.get("min").getAsInt() : 1, j.has("max") ? j.get("max").getAsInt() : 1));
                }
                pools.add(new Pool(tables, entries, o.get("chance").getAsFloat(), o.get("rolls").getAsInt()));
            }
        } catch (Exception ex) {
            Calibre.LOGGER.error("Could not read calibre_gen/loot.json", ex);
        }
        return pools;
    }
}
